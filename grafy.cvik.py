import numpy as np
import matplotlib.pyplot as plt
from matplotlib.colors import LogNorm # <--- lepší škálování

Mat1 = np.loadtxt('/Mat1.csv', delimiter=',')
Mat2 = np.loadtxt('/Mat2.csv', delimiter=',')
Mat3 = np.loadtxt('/Mat3.csv', delimiter=',')

seznam_matic = [Mat1, Mat2, Mat3]
### všechny grafy vykreslím najednou
nazvy = ["Sit1", "Sit2", "Sit3"]

### aby bylo dodrženo škálování, musíme nastavit lokální min a max
min_val = min(Mat1.min(), Mat2.min(), Mat3.min())
max_val = max(Mat1.max(), Mat2.max(), Mat3.max())

log_min = 0.1

print("Nejnižší srážky celkem", min_val)
print("Nejvyšší srážky celkem", max_val)

### pro vykreslení 3D grafů musíme určit osy x,y (prostě matplot)
osa_x = np.arange(256)
osa_y = np.arange(256)

X, Y = np.meshgrid(osa_x, osa_y)

## plátno
fig = plt.figure(figsize=(18, 10), constrained_layout=True)

for i in range(3):
    aktualni_matice = seznam_matic[i]
    #bacha na dvojtečku

    ##heatmap
    ax_2d = fig.add_subplot(2, 3, i + 1)
    mapa = ax_2d.imshow(aktualni_matice, cmap='YlGnBu',
                        norm=LogNorm(vmin=log_min, vmax=max_val), origin='lower')
    ax_2d.set_title(f" Heatmap - {nazvy[i]}")
    ax_2d.set_xlabel("Osa x [px]")
    ax_2d.set_ylabel("Osa y [px]")
    #uff

    #barvy
    stupnice = fig.colorbar(mapa, ax=ax_2d, shrink=0.8)
    stupnice.set_label("Srážky [mm] (log)")

    ###----> 3D povrch
    ax_3d = fig.add_subplot(2, 3, i + 4, projection='3d')

    povrch = ax_3d.plot_surface(X, Y, aktualni_matice, cmap='YlGnBu',
                                norm=LogNorm(vmin=log_min, vmax=max_val),
                                rstride=2, cstride=2, linewidth=0)
    # takhle je to lepší než psát po řádcích lol

    ax_3d.set_title(f"3D povrch - {nazvy[i]}")
    ax_3d.set_xlabel("Osa x [px]")
    ax_3d.set_ylabel("Osa y [px]")
    ax_3d.set_zlabel("Srážky [mm]")

    # Pokud chceš vidět i nižší terén kolem špiček, můžeš z-osu omezit např. na 200,
    # nebo nechat plný rozsah:
    ax_3d.set_zlim(0, max_val)

plt.savefig("vizualizace.png", dpi=300)
plt.show()